export interface TechniqueStyle {
  title: string;
  detail: string;
  windup: number;
  active: number;
  recovery: number;
  range: number;
  width: number;
  strikes: number;
  shape?: HitShape;
}
function style(
  title: string,
  detail: string,
  windup: number,
  active: number,
  recovery: number,
  range = 1,
  width = 1,
  strikes = 0,
  shape?: HitShape,
): TechniqueStyle {
  return {
    title,
    detail,
    windup,
    active,
    recovery,
    range,
    width,
    strikes,
    ...(shape ? { shape } : {}),
  };
}
