export const bossArt = (id: BossId): { poses: string; walk: string } => {
  const version = (["buggy", "kuro", "arlong"] as string[]).includes(id)
    ? { poses: "v6", walk: "v7" }
    : id === "mr1" || id === "crocodile"
      ? { poses: "v9", walk: "v9" }
      : id === "imu"
        ? { poses: "v10", walk: "v10" }
        : { poses: "v11", walk: "v11" };
  return {
    poses: `assets/bosses/${id}-${version.poses}.png`,
    walk: `assets/bosses/${id}-walk-${version.walk}.png`,
  };
};
